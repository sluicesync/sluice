// runBackupRestoreCell takes a full backup with the form's registry
// into a fresh local store; a refused run must leave no manifest, a
// passing run is restored into targetDSN and graded there.
func runBackupRestoreCell(t *testing.T, f redactSelectorForm, eng ir.Engine, sourceDSN, targetDSN string, counts func(string) func() (int, int)) {
	t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), 3*time.Minute)
	defer cancel()
	store, err := blobcodec.NewLocalStore(t.TempDir())
	if err != nil {
		t.Fatalf("NewLocalStore: %v", err)
	}
	backupErr := (&backup.Backup{Source: eng, SourceDSN: sourceDSN, Store: store, Redactor: f.registry()}).Run(ctx)
	if backupErr == nil {
		if err := (&backup.Restore{Target: eng, TargetDSN: targetDSN, Store: store}).Run(ctx); err != nil {
			t.Fatalf("Restore.Run: %v", err)
		}
	} else if m, err := lineage.ReadManifestIfPresent(ctx, store); err == nil && m != nil {
		t.Errorf("refused backup must not leave a manifest behind (it would carry the unredacted chunks); found %q", m.BackupID)
	}
	assertRedactLaneVerdict(t, f, backupErr, counts(targetDSN))
}
