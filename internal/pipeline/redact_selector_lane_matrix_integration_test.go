const (
	redactLanePlaintext = "alice@example.com"
	redactLaneRedacted  = "REDACTED"
)

const redactLaneSeedMySQL = `
	CREATE TABLE users (
		id    BIGINT       NOT NULL AUTO_INCREMENT,
		email VARCHAR(255) NOT NULL,
		PRIMARY KEY (id)
	) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
	INSERT INTO users (email) VALUES ('` + redactLanePlaintext + `');
`

const redactLaneSeedPG = `
	CREATE TABLE users (
		id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		email VARCHAR(255) NOT NULL
	);
	INSERT INTO users (email) VALUES ('` + redactLanePlaintext + `');
`

// redactSelectorForm is one selector spelling of the same intent —
// "redact users.email" — and the verdict the preflight owes it on a
// source whose tables carry ownNamespace ("" = flat scope).
type redactSelectorForm struct {
	name       string
	schema     string
	wantRefuse bool
}

// redactSelectorForms enumerates the three CLI-producible spellings for
// a run that reads readNamespace (what the operator would write for
// "this database/schema") on a source whose tables are stamped with
// stampedNamespace ("" for single-database MySQL, "public" for PG).
func redactSelectorForms(readNamespace, stampedNamespace string) []redactSelectorForm {
	return []redactSelectorForm{
		{name: "bare", schema: ""},
		// The NEW-1 cell: on a flat-scope source the qualified form can
		// match no bulk row, so it MUST refuse; on a namespaced source
		// it resolves and must redact.
		{name: "qualified-own", schema: readNamespace, wantRefuse: stampedNamespace == ""},
		{name: "qualified-foreign", schema: "other_ns", wantRefuse: true},
	}
}

func (f redactSelectorForm) registry() *redact.Registry {
	r := redact.New()
	r.Set(f.schema, "users", "email", redact.Static{Value: redactLaneRedacted})
	return r
}

// assertRedactLaneVerdict is the per-cell oracle. counts returns
// (raw, redacted) row counts on the target; a missing target table
// counts as (0, 0).
func assertRedactLaneVerdict(t *testing.T, f redactSelectorForm, runErr error, counts func() (raw, redacted int)) {
	t.Helper()
	raw, redacted := counts()
	if raw != 0 {
		t.Errorf("%d row(s) landed with the PLAINTEXT value — the silent-loss shape this matrix exists to catch (run err: %v)", raw, runErr)
	}
	if f.wantRefuse {
		if runErr == nil {
			t.Fatalf("selector %q must be refused at preflight (it can match no row on this lane); run returned nil", f.schema+".users.email")
		}
		if !errors.Is(runErr, errRedactSelectorUnresolved) {
			t.Fatalf("want errRedactSelectorUnresolved; got: %v", runErr)
		}
		if redacted != 0 {
			t.Errorf("refused run must move no rows; found %d redacted row(s) on the target", redacted)
		}
		return
	}
	if runErr != nil {
		t.Fatalf("selector %q must pass preflight and redact; run refused: %v", f.schema+".users.email", runErr)
	}
	if redacted == 0 {
		t.Fatal("run passed but no redacted row reached the target (nothing was copied?)")
	}
}

func redactLaneCountsMySQL(dsn string) func() (raw, redacted int) {
	return func() (int, int) {
		db, err := sql.Open("mysql", dsn)
		if err != nil {
			return 0, 0
		}
		defer func() { _ = db.Close() }()
		ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
		defer cancel()
		var raw, red int
		if err := db.QueryRowContext(
			ctx,
			"SELECT SUM(email = ?), SUM(email = ?) FROM users", redactLanePlaintext, redactLaneRedacted,
		).Scan(&raw, &red); err != nil {
			return 0, 0 // table absent (refused run) or empty
		}
		return raw, red
	}
}

func redactLaneCountsPG(dsn string) func() (raw, redacted int) {
	return func() (int, int) {
		db, err := sql.Open("pgx", dsn)
		if err != nil {
			return 0, 0
		}
		defer func() { _ = db.Close() }()
		ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
		defer cancel()
		var raw, red int
		if err := db.QueryRowContext(
			ctx,
			"SELECT count(*) FILTER (WHERE email = $1), count(*) FILTER (WHERE email = $2) FROM users",
			redactLanePlaintext, redactLaneRedacted,
		).Scan(&raw, &red); err != nil {
			return 0, 0
		}
		return raw, red
	}
}

// freshMySQLTarget creates an empty database on the source's server and
// returns a DSN for it, so each cell starts from a clean target.
func freshMySQLTarget(t *testing.T, sourceDSN, name string) string {
	t.Helper()
	applyDDLMySQL(t, sourceDSN, "CREATE DATABASE "+name)
	dsn, err := buildMySQLDSN(sourceDSN, name)
	if err != nil {
		t.Fatalf("build target DSN: %v", err)
	}
	return dsn
}

// freshPGTarget (the Postgres twin) already exists in
// migrate_where_pg_integration_test.go with the same contract.

func engineOrFatal(t *testing.T, name string) ir.Engine {
	t.Helper()
	eng, ok := engines.Get(name)
	if !ok {
		t.Fatalf("%s engine not registered", name)
	}
	return eng
}

// TestRedactSelectorLaneMatrix_BulkMySQL — the lane NEW-1 leaked on:
// single-database MySQL stamps Table.Schema = "", so the bulk copy
// hands "" to the registry.
func TestRedactSelectorLaneMatrix_BulkMySQL(t *testing.T) {
	sourceDSN, _, cleanup := startMySQL(t)
	defer cleanup()
	applyDDLMySQL(t, sourceDSN, redactLaneSeedMySQL)
	eng := engineOrFatal(t, "mysql")

	for i, f := range redactSelectorForms("source_db", "") {
		t.Run(f.name, func(t *testing.T) {
			targetDSN := freshMySQLTarget(t, sourceDSN, fmt.Sprintf("tgt_bulk_%d", i))
			ctx, cancel := context.WithTimeout(context.Background(), 2*time.Minute)
			defer cancel()
			err := (&Migrator{
				Source: eng, Target: eng, SourceDSN: sourceDSN, TargetDSN: targetDSN,
				Redactor: f.registry(),
			}).Run(ctx)
			assertRedactLaneVerdict(t, f, err, redactLaneCountsMySQL(targetDSN))
		})
	}
}

