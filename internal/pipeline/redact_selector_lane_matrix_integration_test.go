// Selector-form × lane matrix for --redact (audit 2026-08-27 NEW-1).
//
// The defect: the redact preflight resolved a rule by (table, column)
// and ignored its schema, while every row-emitting lane hands
// [redact.Registry.Get] the table's stamped namespace — "" on a MySQL
// source in single-database mode. A schema-qualified rule
// (`source_db.users.email`) therefore passed preflight and then missed
// the registry key on every bulk-copy and backup row, while CDC rows
// (binlog rows carry the database name) hit it: the column shipped
// UNREDACTED at exit 0 on exactly the lanes that move the bulk of the
// data. The fix is upstream — the preflight resolves a qualified rule
// against a table in THAT namespace, refuses it on a flat-scope
// source, and now runs on the backup lane too — so the pin is per
// cell: the value is either redacted on the target, or the run
// refuses before any row moves. NEVER raw.
//
// Lanes: bulk copy on MySQL and on Postgres (Migrator), CDC on MySQL
// (Streamer cold start + a live insert), backup chunk write on MySQL
// and on Postgres (Backup, read back through Restore — a reader that
// is not the writer). Selector forms: bare `table.column`, qualified
// with the namespace the run reads, qualified with a foreign
// namespace. The expected verdict per cell is stated explicitly so a
// regression in EITHER direction (the flat-scope cell passing again,
// or the bare form being refused) is red.
//
// Mutation run 2026-09-02: restoring the schema-blind lookup in
// migcore.findSchemaTable turned the qualified-own × bulk-MySQL and
// × backup-MySQL cells red on THIS file's "row(s) landed with the
// PLAINTEXT value" assertion (plus every qualified-foreign cell on
// both engines); the bare cells stayed green, and they assert the
// pass direction explicitly, so a preflight that started refusing the
// bare form is red too.

