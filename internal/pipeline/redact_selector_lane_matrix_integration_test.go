// TestRedactSelectorLaneMatrix_CDCMySQL — sync cold start (bulk copy
// of the seed row) followed by a live INSERT that arrives through the
// binlog with Schema = "source_db". Pre-fix this is the lane that DID
// redact the qualified-own form while its own cold-start bulk copy did
// not; post-fix the form is refused before the cold start moves a row,
// and the bare form redacts on both halves.
func TestRedactSelectorLaneMatrix_CDCMySQL(t *testing.T) {
	sourceDSN, _, cleanup := startMySQLBinlog(t)
	defer cleanup()
	applyDDLMySQL(t, sourceDSN, redactLaneSeedMySQL)
	eng := engineOrFatal(t, "mysql")

	for i, f := range redactSelectorForms("source_db", "") {
		t.Run(f.name, func(t *testing.T) {
			targetDSN := freshMySQLTarget(t, sourceDSN, fmt.Sprintf("tgt_cdc_%d", i))
			ctx, cancel := context.WithCancel(context.Background())
			defer cancel()
			runErr := make(chan error, 1)
			go func() {
				runErr <- (&Streamer{
					Source: eng, Target: eng, SourceDSN: sourceDSN, TargetDSN: targetDSN,
					StreamID: fmt.Sprintf("redact-lane-%d", i),
					Redactor: f.registry(),
				}).Run(ctx)
			}()

			counts := redactLaneCountsMySQL(targetDSN)
			if f.wantRefuse {
				select {
				case err := <-runErr:
					assertRedactLaneVerdict(t, f, err, counts)
				case <-time.After(90 * time.Second):
					t.Fatal("streamer did not refuse within 90s (preflight let the rule through?)")
				}
				return
			}

			// Cold start lands the seed row through the bulk-copy half.
			if !waitForRowCountMySQL(t, targetDSN, "users", 1, 60*time.Second) {
				t.Fatalf("cold start never delivered the seed row; run err: %v", drainRunErr(runErr))
			}
			// The CDC half: a binlog row carrying Schema = "source_db".
			applyDDLMySQL(t, sourceDSN, "INSERT INTO users (email) VALUES ('"+redactLanePlaintext+"');")
			if !waitForRowCountMySQL(t, targetDSN, "users", 2, 60*time.Second) {
				t.Fatalf("CDC never delivered the live insert; run err: %v", drainRunErr(runErr))
			}
			cancel()
			select {
			case <-runErr:
			case <-time.After(30 * time.Second):
				t.Fatal("streamer did not return after cancel")
			}
			assertRedactLaneVerdict(t, f, nil, counts)
			if _, redacted := counts(); redacted != 2 {
				t.Errorf("want both the bulk-copied and the CDC row redacted; got %d", redacted)
			}
		})
	}
}

// drainRunErr returns a run error that has already arrived, or nil.
func drainRunErr(runErr <-chan error) error {
	select {
	case err := <-runErr:
		return err
	default:
		return nil
	}
}

