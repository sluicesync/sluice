package diff

// Which of a target table's unique keys the source still enforces
// (UNIQUE-KEY-STOPPED-WINDOW-DOOR).
//
// # Why it matters
//
// Every sluice target applies a source INSERT as an upsert, and an upsert
// resolves a conflict through ANY unique key the target has. A target key
// the source does not enforce is therefore a merge waiting for its first
// duplicate: the source holds two rows the key forbids, and the target
// keeps one of them, overwritten by the other (SOURCE-DROPPED-UNIQUE-KEY-
// MERGE). The usual cause is a source `DROP INDEX` the stream never saw —
// made while the stream was stopped, or on a source whose change stream
// carries no DDL — and the other is a target pre-created with a key the
// source never had.
//
// # The rule: a target key is safe when a source key implies it
//
// The question is not "does the source have the same key" but "can two
// distinct source rows collide on this target key". They cannot when the
// source enforces a key S whose parts are a SUBSET of the target key T's:
// rows distinct on S are distinct on any superset of S. So T is covered
// when some source key S (its primary key or a unique index) has, for
// every part, a part of T it implies:
//
//   - a plain column implies the same column (names compared without case:
//     every writer keeps the source's column names, and a case-only
//     difference between two columns of one table is not a shape any
//     engine pair here produces);
//   - a prefix part `c(n)` implies `c(m)` for m ≥ n and the whole column
//     `c` (unique on the first n characters is stricter than unique on
//     more); a whole-column source part implies only a whole-column target
//     part;
//   - an expression part implies the same expression, compared as text when
//     both sides were read in one dialect (whitespace, identifier quoting
//     and the writer's own `(expr) COLLATE <hidden>` pin removed — the
//     normalization [renderIndexColumns] applies for `schema diff`);
//   - a part with an index collation (SQLite NOCASE / RTRIM) implies the
//     same column with that collation or none (a case-insensitive unique
//     forbids more, so it implies the binary one), never a different one.
//
// And for the key as a whole: a PARTIAL source key (a predicate) enforces
// uniqueness only inside its predicate, so it covers a target key only
// under the same predicate (compared as text in one dialect); a target key
// that is NULLS NOT DISTINCT is covered only by a source key that is too.
// A full source key covers a partial target key — the target is weaker.
//
// # Across dialects
//
// An expression or predicate read from another dialect cannot be compared
// as text (a MySQL `lower(`k`)` and a Postgres `lower((k)::text)` are one
// key). There, and only there, the key's NAME is the identity: T is
// covered by a same-named source key whose plain parts imply T's position
// by position and whose expression parts sit at the same positions. Every
// schema writer keeps a secondary index's name, so a key sluice created
// matches. Stated so it cannot be read as broader: this fallback cannot
// see a cross-dialect expression or predicate REDEFINED under its old name
// (a miss), and refuses one RENAMED on either side (a loud false refusal,
// which the acceptance flag answers).
//
// # What is exempt
//
// A target key with a part on a column the source table does not have,
// when that column is generated by the target on every insert — an
// AUTO_INCREMENT / serial / identity surrogate, MySQL's invisible
// generated primary key — cannot collide: no source row supplies it. A
// target-only column of any other kind takes its default, which can be the
// same for every row, so a key on it is judged like any other (and the
// subset rule still covers a key that only ADDS such a column to a key the
// source enforces, which is the `--inject-shard-column` composite key).
//
// Not compared, each owned elsewhere: column collations (the key-collation
// guard), a functional part's hidden collation (the functional-key guard),
// DESC and NULLS ordering (they do not change which rows may coexist).

import (
	"strings"

	"sluicesync.dev/sluice/internal/ir"
)

// UncoveredTargetUniqueKeys returns the target table's unique keys — its
// primary key and every unique index — that no unique key of the source
// table implies (see the file comment for the rule). Both tables are
// read-back IR from their own engine's schema reader. A nil source table
// returns nil: a table the source no longer has is not this question.
func UncoveredTargetUniqueKeys(source, target *ir.Table) []*ir.Index {
	if source == nil || target == nil {
		return nil
	}
	sourceKeys := uniqueKeysOf(source)
	sourceCols := make(map[string]bool, len(source.Columns))
	for _, c := range source.Columns {
		if c != nil {
			sourceCols[strings.ToLower(c.Name)] = true
		}
	}
	var out []*ir.Index
	for _, t := range uniqueKeysOf(target) {
		if keyHasTargetGeneratedColumn(t, target, sourceCols) {
			continue
		}
		covered := false
		for _, s := range sourceKeys {
			if sourceKeyCovers(s, t) {
				covered = true
				break
			}
		}
		if !covered {
			out = append(out, t)
		}
	}
	return out
}

// uniqueKeysOf lists a table's primary key and unique indexes, skipping an
// index that repeats the primary key (a reader that lists it twice).
func uniqueKeysOf(t *ir.Table) []*ir.Index {
	var out []*ir.Index
	if t.PrimaryKey != nil && len(t.PrimaryKey.Columns) > 0 {
		out = append(out, t.PrimaryKey)
	}
	for _, idx := range t.Indexes {
		if idx == nil || !idx.Unique || len(idx.Columns) == 0 || idx == t.PrimaryKey {
			continue
		}
		out = append(out, idx)
	}
	return out
}

// keyHasTargetGeneratedColumn reports whether key reads a column the source
// table lacks and the target generates on every insert.
func keyHasTargetGeneratedColumn(key *ir.Index, table *ir.Table, sourceCols map[string]bool) bool {
	for _, p := range key.Columns {
		if p.Column == "" || sourceCols[strings.ToLower(p.Column)] {
			continue
		}
		for _, c := range table.Columns {
			if c == nil || !strings.EqualFold(c.Name, p.Column) {
				continue
			}
			if c.Identity != nil {
				return true
			}
			if it, ok := ir.UnwrapDomain(c.Type).(ir.Integer); ok && it.AutoIncrement {
				return true
			}
		}
	}
	return false
}

// sourceKeyCovers reports whether source key s implies target key t.
func sourceKeyCovers(s, t *ir.Index) bool {
	if t.ConstraintNullsNotDistinct && !s.ConstraintNullsNotDistinct {
		return false
	}
	if structurallyCovers(s, t) {
		return true
	}
	return nameCovers(s, t)
}

// structurallyCovers is the subset rule, comparing every part (and a
// partial source key's predicate) within one dialect.
func structurallyCovers(s, t *ir.Index) bool {
	if sp := strings.TrimSpace(s.Predicate); sp != "" {
		tp := strings.TrimSpace(t.Predicate)
		if tp == "" || s.PredicateDialect != t.PredicateDialect || normalizeKeyText(sp, "") != normalizeKeyText(tp, "") {
			return false
		}
	}
	used := make([]bool, len(t.Columns))
	for _, sp := range s.Columns {
		found := false
		for i, tp := range t.Columns {
			if !used[i] && partImplies(sp, tp) {
				used[i] = true
				found = true
				break
			}
		}
		if !found {
			return false
		}
	}
	return true
}

// partImplies reports whether a source key part implies a target key part
// (the per-part rules in the file comment). Expression parts compare only
// within one dialect.
func partImplies(s, t ir.IndexColumn) bool {
	if s.Collation != "" || t.Collation != "" {
		if t.Collation != "" && !strings.EqualFold(s.Collation, t.Collation) {
			return false
		}
	}
	if s.Expression != "" || t.Expression != "" {
		if s.Expression == "" || t.Expression == "" || s.ExpressionDialect != t.ExpressionDialect {
			return false
		}
		// The peer's hidden collation strips a side that records none (a
		// vtgate read), as renderIndexColumns does.
		sh, th := s.HiddenCollation, t.HiddenCollation
		if sh == "" {
			sh = th
		}
		if th == "" {
			th = sh
		}
		return normalizeKeyText(s.Expression, sh) == normalizeKeyText(t.Expression, th)
	}
	if !strings.EqualFold(s.Column, t.Column) {
		return false
	}
	switch {
	case s.Length == t.Length:
		return true
	case s.Length > 0:
		return t.Length == 0 || t.Length > s.Length
	default:
		return false
	}
}

// nameCovers is the cross-dialect fallback: a same-named key with the same
// shape, whose plain parts imply the target's position by position and
// whose expression parts — read in another dialect — sit at the same
// positions. It applies only when something in the pair could not be
// compared as text; a same-dialect pair is the structural rule's alone.
func nameCovers(s, t *ir.Index) bool {
	if s.Name == "" || !strings.EqualFold(s.Name, t.Name) || len(s.Columns) != len(t.Columns) {
		return false
	}
	crossDialect := false
	if strings.TrimSpace(s.Predicate) != "" {
		if strings.TrimSpace(t.Predicate) == "" {
			return false // a partial source key never implies a full target key
		}
		if s.PredicateDialect != t.PredicateDialect {
			crossDialect = true
		} else if normalizeKeyText(s.Predicate, "") != normalizeKeyText(t.Predicate, "") {
			return false
		}
	}
	for i, sp := range s.Columns {
		tp := t.Columns[i]
		if (sp.Expression == "") != (tp.Expression == "") {
			return false
		}
		if sp.Expression != "" {
			if sp.ExpressionDialect == tp.ExpressionDialect {
				return false // comparable as text, and the structural rule said no
			}
			crossDialect = true
			continue
		}
		if !partImplies(sp, tp) {
			return false
		}
	}
	return crossDialect
}

// normalizeKeyText reduces an expression or predicate to the form two reads
// of one dialect agree on: the writer's outer `(expr) COLLATE <hidden>` pin
// removed, then, outside single-quoted literals, lower case without
// whitespace, identifier quotes or redundant outer parentheses. A literal
// is kept byte for byte: `k = 'A'` and `k = 'a'` are different keys.
func normalizeKeyText(expr, hiddenCollation string) string {
	e := stripOuterCollate(expr, hiddenCollation)
	var b strings.Builder
	inLiteral := false
	for _, r := range e {
		if r == '\'' {
			inLiteral = !inLiteral
			b.WriteRune(r)
			continue
		}
		if inLiteral {
			b.WriteRune(r)
			continue
		}
		switch r {
		case ' ', '\t', '\n', '\r', '`', '"':
			continue
		}
		b.WriteString(strings.ToLower(string(r)))
	}
	out := b.String()
	for strings.HasPrefix(out, "(") && strings.HasSuffix(out, ")") && balancedOuter(out) {
		out = out[1 : len(out)-1]
	}
	return out
}

// balancedOuter reports whether s's first '(' closes at its last byte.
func balancedOuter(s string) bool {
	depth := 0
	for i := 0; i < len(s); i++ {
		switch s[i] {
		case '(':
			depth++
		case ')':
			depth--
			if depth == 0 && i != len(s)-1 {
				return false
			}
		}
	}
	return depth == 0
}
